-- Схема этапа 1.
--
-- Каждая запись компании несёт company_id. Ссылки между таблицами компании идут парой
-- (id, company_id) → (id, company_id): строка не может сослаться на запись чужой компании даже по
-- ошибке в коде. Поэтому у таблиц, на которые ссылаются, есть unique (id, company_id).
-- Исключение — «кто сделал» (подтвердил, принял, записал): это может быть владелец без компании,
-- такие ссылки обычные, на users (id).
--
-- Деньги — bigint в тенге, количество — целые штуки. Время — местное (Asia/Almaty), без пояса.
-- Записи, которые создаёт телефон агента или экспедитора, несут uuid с телефона: по нему сервер
-- узнаёт повторную отправку и не создаёт дубль.
--
-- Статусы — строки с CHECK. Новое значение enum в коде = новая миграция с новым CHECK.
-- Долг магазина не хранится: начальный долг + доставлено − оплачено − возвращено.

-- ---------------------------------------------------------------- компании и люди

create table companies (
    id         bigint generated by default as identity primary key,
    name       varchar(200) not null,
    director   varchar(200),
    phone      varchar(32),
    -- клиент этой компании в CRM производства; null — своя доставка
    crm_client varchar(200),
    own        boolean      not null default false,
    active     boolean      not null default true,
    created_at timestamp    not null
);

create table company_settings (
    id                     bigint generated by default as identity primary key,
    company_id             bigint  not null unique references companies (id),
    visit_radius_m         integer not null default 200 check (visit_radius_m between 10 and 5000),
    shelf_photo_required   boolean not null default false,
    refuse_reason_required boolean not null default true,
    delivery_days          integer not null default 1 check (delivery_days between 1 and 7),
    default_credit_limit   bigint  not null default 50000 check (default_credit_limit >= 0),
    allow_credit           boolean not null default true,
    approval_over_limit    boolean not null default true,
    agent_discount         boolean not null default false,
    cash_tolerance         bigint  not null default 0 check (cash_tolerance >= 0),
    accept_kaspi           boolean not null default true,
    auto_receipt           boolean not null default true
);

-- Сотрудники всех компаний. company_id пуст только у владельца (SUPER_ADMIN).
create table users (
    id                   bigint generated by default as identity primary key,
    company_id           bigint references companies (id),
    name                 varchar(200) not null,
    role                 varchar(20)  not null
        check (role in ('SUPER_ADMIN', 'DIRECTOR', 'OPERATOR', 'STOREKEEPER', 'AGENT', 'EXPEDITOR')),
    -- вход по телефону: всегда +7 и 10 цифр
    phone                varchar(12)  not null unique check (phone ~ '^\+7[0-9]{10}$'),
    login                varchar(64) unique check (login = lower(login)),
    password_hash        varchar(100),
    must_change_password boolean      not null default true,
    active               boolean      not null default true,
    -- последняя синхронизация телефона и сколько записей на нём ждали отправки
    last_sync            timestamp,
    unsent               integer      not null default 0 check (unsent >= 0),
    created_at           timestamp    not null,
    unique (id, company_id),
    check ((role = 'SUPER_ADMIN') = (company_id is null))
);
create index users_company_idx on users (company_id);

-- ---------------------------------------------------------------- регионы, маршруты, магазины

create table regions (
    id         bigint generated by default as identity primary key,
    company_id bigint       not null references companies (id),
    name       varchar(120) not null,
    unique (id, company_id),
    unique (company_id, name)
);

create table routes (
    id         bigint generated by default as identity primary key,
    company_id bigint       not null references companies (id),
    region_id  bigint       not null,
    name       varchar(120) not null,
    agent_id   bigint,
    -- дни обхода: биты пн=1, вт=2, ср=4, чт=8, пт=16, сб=32, вс=64
    days       integer      not null default 0 check (days between 0 and 127),
    active     boolean      not null default true,
    unique (id, company_id),
    unique (company_id, name),
    foreign key (region_id, company_id) references regions (id, company_id),
    foreign key (agent_id, company_id) references users (id, company_id)
);
create index routes_region_idx on routes (region_id);
create index routes_agent_idx on routes (agent_id);

create table price_types (
    id         bigint generated by default as identity primary key,
    company_id bigint      not null references companies (id),
    code       varchar(16) not null check (code in ('WHOLESALE', 'RETAIL')),
    name       varchar(60) not null,
    unique (id, company_id),
    unique (company_id, code)
);

create table outlets (
    id            bigint generated by default as identity primary key,
    company_id    bigint       not null references companies (id),
    uuid          uuid         not null unique,
    name          varchar(200) not null,
    -- ИП / ТОО
    legal         varchar(200),
    bin           varchar(20),
    owner         varchar(200),
    phone         varchar(64),
    phone2        varchar(64),
    address       varchar(300),
    -- в сёлах адрес = GPS + ориентир + фото фасада
    landmark      varchar(300),
    lat           double precision check (lat between -90 and 90),
    lng           double precision check (lng between -180 and 180),
    facade_photo  varchar(300),
    price_type_id bigint       not null,
    credit_limit  bigint       not null default 0 check (credit_limit >= 0),
    -- отсрочка оплаты, дней
    payment_days  integer      not null default 0 check (payment_days between 0 and 365),
    status        varchar(10)  not null check (status in ('ACTIVE', 'PENDING', 'CLOSED')),
    created_on    date         not null,
    created_by    varchar(200),
    unique (id, company_id),
    foreign key (price_type_id, company_id) references price_types (id, company_id)
);
create index outlets_company_idx on outlets (company_id, status);

-- Магазины маршрута по порядку обхода. Пока у магазина один маршрут (unique outlet_id).
create table route_outlets (
    id         bigint generated by default as identity primary key,
    company_id bigint  not null references companies (id),
    route_id   bigint  not null,
    outlet_id  bigint  not null unique,
    position   integer not null check (position >= 0),
    foreign key (route_id, company_id) references routes (id, company_id),
    foreign key (outlet_id, company_id) references outlets (id, company_id)
);
create index route_outlets_route_idx on route_outlets (route_id, position);
create index route_outlets_company_idx on route_outlets (company_id);

-- Долг магазина на день импорта из Doctor Sales (или ввода вручную).
create table outlet_opening_debts (
    id         bigint generated by default as identity primary key,
    company_id bigint not null references companies (id),
    outlet_id  bigint not null,
    amount     bigint not null check (amount <> 0),
    -- с этой даты считается отсрочка
    as_of      date   not null,
    note       varchar(200),
    foreign key (outlet_id, company_id) references outlets (id, company_id)
);
create index outlet_opening_debts_outlet_idx on outlet_opening_debts (outlet_id);
create index outlet_opening_debts_company_idx on outlet_opening_debts (company_id);

-- ---------------------------------------------------------------- товары и цены

create table products (
    id         bigint generated by default as identity primary key,
    company_id bigint       not null references companies (id),
    name       varchar(200) not null,
    category   varchar(120) not null,
    unit       varchar(16)  not null default 'шт',
    per_box    integer      not null default 1 check (per_box > 0),
    barcode    varchar(32),
    -- код товара в CRM производства; null — товар другого поставщика
    crm_code   varchar(32),
    active     boolean      not null default true,
    unique (id, company_id),
    unique (company_id, crm_code)
);

-- Цена действует с valid_from до следующей записи того же товара и типа цен.
create table prices (
    id            bigint generated by default as identity primary key,
    company_id    bigint not null references companies (id),
    product_id    bigint not null,
    price_type_id bigint not null,
    valid_from    date   not null,
    price         bigint not null check (price >= 0),
    unique (product_id, price_type_id, valid_from),
    foreign key (product_id, company_id) references products (id, company_id),
    foreign key (price_type_id, company_id) references price_types (id, company_id)
);
create index prices_company_idx on prices (company_id);

-- ---------------------------------------------------------------- машины и склады

create table vehicles (
    id           bigint generated by default as identity primary key,
    company_id   bigint      not null references companies (id),
    plate        varchar(20) not null,
    model        varchar(100),
    -- закреплённый экспедитор
    expeditor_id bigint unique,
    active       boolean     not null default true,
    unique (id, company_id),
    unique (company_id, plate),
    foreign key (expeditor_id, company_id) references users (id, company_id)
);

-- Основной и негодный — по одному на компанию, склад машины — по одному на машину.
create table warehouses (
    id         bigint generated by default as identity primary key,
    company_id bigint       not null references companies (id),
    type       varchar(10)  not null check (type in ('MAIN', 'DEFECT', 'VEHICLE')),
    name       varchar(120) not null,
    vehicle_id bigint unique,
    unique (id, company_id),
    foreign key (vehicle_id, company_id) references vehicles (id, company_id),
    check ((type = 'VEHICLE') = (vehicle_id is not null))
);
create unique index warehouses_main_defect_uq on warehouses (company_id, type) where type <> 'VEHICLE';

create table stock_balances (
    id           bigint generated by default as identity primary key,
    company_id   bigint  not null references companies (id),
    warehouse_id bigint  not null,
    product_id   bigint  not null,
    qty          integer not null default 0 check (qty >= 0),
    unique (warehouse_id, product_id),
    foreign key (warehouse_id, company_id) references warehouses (id, company_id),
    foreign key (product_id, company_id) references products (id, company_id)
);
create index stock_balances_company_idx on stock_balances (company_id);

-- ---------------------------------------------------------------- приходы

create table receipts (
    id           bigint generated by default as identity primary key,
    company_id   bigint      not null references companies (id),
    number       varchar(32) not null,
    source       varchar(10) not null check (source in ('CRM', 'SUPPLIER', 'MANUAL')),
    status       varchar(10) not null check (status in ('DRAFT', 'CONFIRMED')),
    doc_date     date        not null,
    -- документ-основание: «Отгрузка CRM, заказ №…» или накладная поставщика
    basis        varchar(300),
    supplier     varchar(200),
    warehouse_id bigint      not null,
    confirmed_by bigint,
    confirmed_at timestamp,
    created_at   timestamp   not null,
    unique (id, company_id),
    unique (company_id, number),
    foreign key (warehouse_id, company_id) references warehouses (id, company_id),
    foreign key (confirmed_by) references users (id)
);

create table receipt_items (
    id         bigint generated by default as identity primary key,
    company_id bigint  not null references companies (id),
    receipt_id bigint  not null,
    product_id bigint  not null,
    -- по документу
    expected   integer not null check (expected >= 0),
    -- фактически принято; null — ещё не пересчитали
    actual     integer check (actual >= 0),
    unique (receipt_id, product_id),
    foreign key (receipt_id, company_id) references receipts (id, company_id),
    foreign key (product_id, company_id) references products (id, company_id)
);
create index receipt_items_company_idx on receipt_items (company_id);

-- ---------------------------------------------------------------- визиты и заказы

create table visits (
    id            bigint generated by default as identity primary key,
    company_id    bigint      not null references companies (id),
    uuid          uuid        not null unique,
    agent_id      bigint      not null,
    outlet_id     bigint      not null,
    route_id      bigint,
    started_at    timestamp   not null,
    finished_at   timestamp,
    lat           double precision check (lat between -90 and 90),
    lng           double precision check (lng between -180 and 180),
    -- расстояние до точки магазина, метров
    distance_m    integer check (distance_m >= 0),
    result        varchar(10) not null check (result in ('ORDER', 'NO_ORDER')),
    refuse_reason varchar(200),
    shelf_photo   varchar(300),
    unique (id, company_id),
    foreign key (agent_id, company_id) references users (id, company_id),
    foreign key (outlet_id, company_id) references outlets (id, company_id),
    foreign key (route_id, company_id) references routes (id, company_id)
);
create index visits_day_idx on visits (company_id, started_at);
create index visits_outlet_idx on visits (outlet_id);

create table orders (
    id             bigint generated by default as identity primary key,
    company_id     bigint      not null references companies (id),
    uuid           uuid        not null unique,
    number         varchar(32) not null,
    outlet_id      bigint      not null,
    agent_id       bigint,
    visit_id       bigint,
    created_at     timestamp   not null,
    delivery_date  date        not null,
    status         varchar(16) not null check (status in ('ACCEPTED', 'NEEDS_APPROVAL', 'ASSEMBLED', 'IN_TRIP',
                                                          'DELIVERED', 'PARTIAL', 'REFUSED', 'CANCELLED')),
    payment_method varchar(8)  not null check (payment_method in ('CASH', 'KASPI', 'CREDIT')),
    comment        varchar(500),
    refuse_reason  varchar(300),
    unique (id, company_id),
    unique (company_id, number),
    foreign key (outlet_id, company_id) references outlets (id, company_id),
    foreign key (agent_id, company_id) references users (id, company_id),
    foreign key (visit_id, company_id) references visits (id, company_id)
);
create index orders_delivery_idx on orders (company_id, delivery_date);
create index orders_created_idx on orders (company_id, created_at);
create index orders_outlet_idx on orders (outlet_id);

create table order_items (
    id         bigint generated by default as identity primary key,
    company_id bigint  not null references companies (id),
    order_id   bigint  not null,
    product_id bigint  not null,
    qty        integer not null check (qty > 0),
    -- цена за штуку по типу цен магазина на день заказа
    price      bigint  not null check (price >= 0),
    -- скидка на строку, ₸ (может ли агент давать скидку — ещё не решено)
    discount   bigint check (discount >= 0),
    unique (order_id, product_id),
    foreign key (order_id, company_id) references orders (id, company_id),
    foreign key (product_id, company_id) references products (id, company_id),
    check (discount is null or discount <= qty * price)
);
create index order_items_company_idx on order_items (company_id);

-- История заказа: кто и что сделал.
create table order_events (
    id         bigint generated by default as identity primary key,
    company_id bigint       not null references companies (id),
    order_id   bigint       not null,
    event_at   timestamp    not null,
    user_id    bigint,
    -- подпись: имя сотрудника или «Система», «Склад»
    who_name   varchar(200) not null,
    message    varchar(500) not null,
    foreign key (order_id, company_id) references orders (id, company_id),
    foreign key (user_id) references users (id)
);
create index order_events_order_idx on order_events (order_id, event_at);
create index order_events_company_idx on order_events (company_id);

-- ---------------------------------------------------------------- рейсы и доставка

-- Рейс: одна машина и один экспедитор на день.
create table trips (
    id           bigint generated by default as identity primary key,
    company_id   bigint      not null references companies (id),
    number       varchar(32) not null,
    trip_date    date        not null,
    expeditor_id bigint      not null,
    vehicle_id   bigint      not null,
    status       varchar(10) not null check (status in ('LOADING', 'ON_ROAD', 'RETURNED', 'CLOSED')),
    started_at   timestamp,
    returned_at  timestamp,
    closed_at    timestamp,
    unique (id, company_id),
    unique (company_id, number),
    foreign key (expeditor_id, company_id) references users (id, company_id),
    foreign key (vehicle_id, company_id) references vehicles (id, company_id)
);
create index trips_date_idx on trips (company_id, trip_date);

-- Заказы рейса по порядку точек.
create table trip_orders (
    id         bigint generated by default as identity primary key,
    company_id bigint  not null references companies (id),
    trip_id    bigint  not null,
    order_id   bigint  not null unique,
    position   integer not null check (position >= 0),
    foreign key (trip_id, company_id) references trips (id, company_id),
    foreign key (order_id, company_id) references orders (id, company_id)
);
create index trip_orders_trip_idx on trip_orders (trip_id, position);
create index trip_orders_company_idx on trip_orders (company_id);

-- Выдача заказа: полностью, частично или отказ магазина. Одна на заказ.
create table deliveries (
    id            bigint generated by default as identity primary key,
    company_id    bigint      not null references companies (id),
    uuid          uuid        not null unique,
    order_id      bigint      not null unique,
    trip_id       bigint,
    status        varchar(10) not null check (status in ('DELIVERED', 'PARTIAL', 'REFUSED')),
    delivered_at  timestamp   not null,
    expeditor_id  bigint,
    refuse_reason varchar(300),
    lat           double precision check (lat between -90 and 90),
    lng           double precision check (lng between -180 and 180),
    unique (id, company_id),
    foreign key (order_id, company_id) references orders (id, company_id),
    foreign key (trip_id, company_id) references trips (id, company_id),
    foreign key (expeditor_id, company_id) references users (id, company_id)
);
create index deliveries_trip_idx on deliveries (trip_id);
create index deliveries_company_idx on deliveries (company_id, delivered_at);

create table delivery_items (
    id          bigint generated by default as identity primary key,
    company_id  bigint  not null references companies (id),
    delivery_id bigint  not null,
    product_id  bigint  not null,
    qty         integer not null check (qty >= 0),
    -- цена за штуку с учётом скидки строки — из неё считается долг
    price       bigint  not null check (price >= 0),
    unique (delivery_id, product_id),
    foreign key (delivery_id, company_id) references deliveries (id, company_id),
    foreign key (product_id, company_id) references products (id, company_id)
);
create index delivery_items_company_idx on delivery_items (company_id);

-- Оплата магазина: за заказ или в счёт старого долга (order_id пуст). «В долг» — не оплата.
create table payments (
    id          bigint generated by default as identity primary key,
    company_id  bigint     not null references companies (id),
    uuid        uuid       not null unique,
    outlet_id   bigint     not null,
    order_id    bigint,
    trip_id     bigint,
    method      varchar(8) not null check (method in ('CASH', 'KASPI')),
    amount      bigint     not null check (amount > 0),
    paid_at     timestamp  not null,
    received_by bigint,
    foreign key (outlet_id, company_id) references outlets (id, company_id),
    foreign key (order_id, company_id) references orders (id, company_id),
    foreign key (trip_id, company_id) references trips (id, company_id),
    foreign key (received_by) references users (id)
);
create index payments_outlet_idx on payments (outlet_id, paid_at);
create index payments_trip_idx on payments (trip_id);
create index payments_company_idx on payments (company_id, paid_at);

-- Негодный товар из магазина (брак и возврат — одно и то же).
create table returns (
    id          bigint generated by default as identity primary key,
    company_id  bigint    not null references companies (id),
    uuid        uuid      not null unique,
    outlet_id   bigint    not null,
    trip_id     bigint,
    order_id    bigint,
    return_date date      not null,
    created_at  timestamp not null,
    received_by bigint,
    unique (id, company_id),
    foreign key (outlet_id, company_id) references outlets (id, company_id),
    foreign key (trip_id, company_id) references trips (id, company_id),
    foreign key (order_id, company_id) references orders (id, company_id),
    foreign key (received_by) references users (id)
);
create index returns_outlet_idx on returns (outlet_id);
create index returns_trip_idx on returns (trip_id);
create index returns_company_idx on returns (company_id, return_date);

create table return_items (
    id         bigint generated by default as identity primary key,
    company_id bigint      not null references companies (id),
    return_id  bigint      not null,
    product_id bigint      not null,
    qty        integer     not null check (qty > 0),
    price      bigint      not null check (price >= 0),
    reason     varchar(10) not null check (reason in ('EXPIRED', 'DEFECT', 'PACKAGING')),
    foreign key (return_id, company_id) references returns (id, company_id),
    foreign key (product_id, company_id) references products (id, company_id)
);
create index return_items_return_idx on return_items (return_id);
create index return_items_company_idx on return_items (company_id);

-- Приём рейса вечером: пересчёт наличных (разница — на экспедиторе), сверка Kaspi, приём товара.
create table cash_handovers (
    id             bigint generated by default as identity primary key,
    company_id     bigint  not null references companies (id),
    trip_id        bigint  not null unique,
    expeditor_id   bigint  not null,
    -- сколько наличных ждали по оплатам рейса на момент приёма
    expected_cash  bigint  not null check (expected_cash >= 0),
    counted_cash   bigint check (counted_cash >= 0),
    -- пересчитано − ожидалось; минус — недостача
    cash_diff      bigint,
    kaspi_expected bigint  not null check (kaspi_expected >= 0),
    kaspi_checked  boolean not null default false,
    goods_checked  boolean not null default false,
    accepted_by    bigint,
    accepted_at    timestamp,
    foreign key (trip_id, company_id) references trips (id, company_id),
    foreign key (expeditor_id, company_id) references users (id, company_id),
    foreign key (accepted_by) references users (id)
);
create index cash_handovers_company_idx on cash_handovers (company_id);
create index cash_handovers_expeditor_idx on cash_handovers (expeditor_id);

-- ---------------------------------------------------------------- движения товара

-- Каждое изменение остатка: откуда, куда, по какому документу. Остатки (stock_balances) меняются
-- в той же транзакции.
create table stock_movements (
    id                bigint generated by default as identity primary key,
    company_id        bigint      not null references companies (id),
    moved_at          timestamp   not null,
    product_id        bigint      not null,
    qty               integer     not null check (qty > 0),
    from_warehouse_id bigint,
    to_warehouse_id   bigint,
    reason            varchar(12) not null
        check (reason in ('RECEIPT', 'LOAD', 'UNLOAD', 'DELIVERY', 'RETURN', 'ADJUST')),
    receipt_id        bigint,
    trip_id           bigint,
    order_id          bigint,
    return_id         bigint,
    user_id           bigint,
    note              varchar(200),
    check (from_warehouse_id is not null or to_warehouse_id is not null),
    foreign key (product_id, company_id) references products (id, company_id),
    foreign key (from_warehouse_id, company_id) references warehouses (id, company_id),
    foreign key (to_warehouse_id, company_id) references warehouses (id, company_id),
    foreign key (receipt_id, company_id) references receipts (id, company_id),
    foreign key (trip_id, company_id) references trips (id, company_id),
    foreign key (order_id, company_id) references orders (id, company_id),
    foreign key (return_id, company_id) references returns (id, company_id),
    foreign key (user_id) references users (id)
