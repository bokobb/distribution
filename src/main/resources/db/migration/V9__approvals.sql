-- «Разрешения»: заказ сверх лимита, заказ закрыт по просрочке, недоплата при выдаче, новый магазин.

-- Первый заказ магазина на проверке — только с оплатой при доставке (раньше было всегда так).
-- Заказ закрывается сам, если просрочка больше overdue_days дней или больше overdue_amount ₸;
-- один заказ открывают директор и владелец, оператор — если включено.
alter table company_settings
    add column first_order_cash  boolean not null default true,
    add column overdue_block     boolean not null default true,
    add column overdue_days      int     not null default 14,
    add column overdue_amount    bigint  not null default 30000,
    add column unblock_director  boolean not null default true,
    add column unblock_operator  boolean not null default false,
    add column underpay_approval boolean not null default true;

-- Почему заказ ждёт разрешения: LIMIT — долг сверх лимита, OVERDUE — магазин закрыт по просрочке.
alter table orders add column hold varchar(16) check (hold in ('LIMIT', 'OVERDUE'));
update orders set hold = 'LIMIT' where status = 'NEEDS_APPROVAL';

-- Решения по разрешениям. Заказы и новые магазины ждут решения в своих таблицах (статус), здесь — что решили.
-- Недоплата при выдаче своей таблицы не имеет: она ждёт здесь же, пока decision пусто.
create table approvals (
    id            bigint generated by default as identity primary key,
    company_id    bigint       not null references companies (id),
    kind          varchar(16)  not null check (kind in ('LIMIT', 'OVERDUE', 'UNDERPAY', 'OUTLET')),
    outlet_id     bigint       not null,
    order_id      bigint,
    title         varchar(300) not null,
    terms         varchar(1000),
    note          varchar(300),
    created_at    timestamp    not null,
    created_by    varchar(150),
    decision      varchar(16),
    decision_text varchar(300),
    decided_at    timestamp,
    decided_by    varchar(150),
    prev_payment  varchar(8),
    foreign key (outlet_id, company_id) references outlets (id, company_id),
    foreign key (order_id, company_id) references orders (id, company_id)
);
create index approvals_open_idx on approvals (company_id) where decision is null;
create index approvals_decided_idx on approvals (company_id, decided_at);
