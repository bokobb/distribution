-- Входы приложения торгового агента и экспедитора на телефонах (как в CRM): пароль вводится один раз,
-- дальше приложение само берёт новый JWT по ключу устройства. В базе — только SHA-256 ключа, сам ключ
-- знает только телефон.
--
-- Ключ закрывается: «Выйти» в приложении, смена пароля (кроме телефона, на котором меняли), сброс пароля
-- директором, отключение сотрудника, смена роли. Не пользовались 180 дней — удаляется при следующем входе.
create table device_sessions (
    id           bigint generated by default as identity primary key,
    company_id   bigint      not null references companies (id),
    user_id      bigint      not null,
    token_hash   varchar(64) not null unique,
    -- модель телефона, как её назвало приложение
    device       varchar(100),
    created_at   timestamp   not null,
    last_used_at timestamp   not null,
    foreign key (user_id, company_id) references users (id, company_id)
);
create index device_sessions_user_idx on device_sessions (user_id, last_used_at);
