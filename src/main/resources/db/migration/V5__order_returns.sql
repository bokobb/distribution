-- Возврат негодного товара, который торговый записал вместе с заказом: магазин отдаёт просрочку, брак или товар с
-- плохой упаковкой, экспедитор забирает его при доставке заказа. Это план — долг не меняется; настоящий возврат
-- (returns) записывает экспедитор у магазина, сколько взял на самом деле. Цена — по прайсу магазина на день заказа.
create table order_return_items (
    id         bigint generated by default as identity primary key,
    company_id bigint      not null references companies (id),
    order_id   bigint      not null,
    product_id bigint      not null,
    qty        integer     not null check (qty > 0),
    price      bigint      not null check (price >= 0),
    reason     varchar(10) not null check (reason in ('EXPIRED', 'DEFECT', 'PACKAGING')),
    unique (order_id, product_id),
    foreign key (order_id, company_id) references orders (id, company_id),
    foreign key (product_id, company_id) references products (id, company_id)
);
create index order_return_items_company_idx on order_return_items (company_id);
