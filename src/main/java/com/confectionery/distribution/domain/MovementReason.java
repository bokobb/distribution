package com.confectionery.distribution.domain;

/** Почему изменился остаток. */
public enum MovementReason {
    /** Приход на основной склад. */
    RECEIPT,
    /** Загрузка машины: основной → машина. */
    LOAD,
    /** Приём рейса: невыданное → основной, негодное → склад негодного. */
    UNLOAD,
    /** Выдача магазину: машина → магазин. */
    DELIVERY,
    /** Негодный товар от магазина: магазин → машина. */
    RETURN,
    /** Ввод остатков, пересчёт. */
    ADJUST
}
