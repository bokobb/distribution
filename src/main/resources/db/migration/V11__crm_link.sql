-- Связь с CRM производства: директор компании — клиент CRM (crm_client_id), выданные ему заказы приходят
-- приходом «ждёт подтверждения» (receipts.crm_order_id), подтверждение с расхождением уходит в CRM (crm_sent_at).

alter table companies add column crm_client_id bigint unique;

alter table receipts
    add column crm_order_id bigint,
    add column crm_sent_at  timestamp,
    add constraint receipts_crm_order_uq unique (company_id, crm_order_id);

-- Журнал входов в админку: паролем или пропуском владельца из CRM.
create table login_log (
    id          bigint generated by default as identity primary key,
    at          timestamp    not null,
    employee_id bigint references users (id),
    via         varchar(16)  not null check (via in ('PASSWORD', 'CRM')),
    who         varchar(200) not null,
    ip          varchar(64)
);
create index login_log_at_idx on login_log (at desc);
