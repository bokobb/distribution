-- GPS торговых и экспедиторов и журнал работы приложения.
--
-- Телефон пишет точку раз в company_settings.gps_interval_min минут и только в рабочий день: от
-- «Начал день» до «Закончил день» (события журнала), не дольше конца даты. Точки хранятся 6 месяцев,
-- журнал — год: старше удаляет ночная задача (TrackCleanup).

alter table company_settings
    add column gps_interval_min integer not null default 5 check (gps_interval_min between 1 and 60);

-- Точка GPS. Повторная отправка той же точки узнаётся по (сотрудник, время точки) и не создаёт дубль.
create table gps_points (
    id          bigint generated by default as identity primary key,
    company_id  bigint           not null references companies (id),
    user_id     bigint           not null,
    -- время на телефоне, когда снята точка
    recorded_at timestamp        not null,
    lat         double precision not null check (lat between -90 and 90),
    lng         double precision not null check (lng between -180 and 180),
    -- точность по телефону, метров
    accuracy_m  integer check (accuracy_m >= 0),
    -- заряд батареи, %
    battery     integer check (battery between 0 and 100),
    received_at timestamp        not null,
    unique (user_id, recorded_at),
    foreign key (user_id, company_id) references users (id, company_id)
);
create index gps_points_company_idx on gps_points (company_id, recorded_at);

-- Журнал приложения: вход и выход, запуск, начало и конец рабочего дня, синхронизация, GPS выключен
-- и включён. uuid — с телефона, как у визитов: повторная отправка не создаёт дубль.
create table app_events (
    id          bigint generated by default as identity primary key,
    company_id  bigint      not null references companies (id),
    uuid        uuid        not null unique,
    user_id     bigint      not null,
    event_at    timestamp   not null,
    kind        varchar(10) not null
        check (kind in ('LOGIN', 'LOGOUT', 'APP_OPEN', 'DAY_START', 'DAY_END', 'SYNC', 'GPS_OFF', 'GPS_ON')),
    app_version varchar(32),
    -- модель телефона
    device      varchar(100),
    -- подробности от телефона: «ждали отправки: 3»
    note        varchar(300),
    received_at timestamp   not null,
    foreign key (user_id, company_id) references users (id, company_id)
);
create index app_events_user_idx on app_events (user_id, event_at);
create index app_events_company_idx on app_events (company_id, event_at);
